def render(project_name: str, entities: list[dict], *, buggy_delete: bool = False) -> dict[str, str]:
    """Return {relative_path: content} for the whole generated project."""
    _check(entities)
    plurals = ", ".join(f'"{plural(e["name"])}": "{e["name"]}"' for e in entities)
    return {
        "app/__init__.py": "",
        "app/__main__.py": MAIN,
        "app/store.py": render_store(entities, buggy_delete=buggy_delete),
        "app/server.py": SERVER.replace("__PLURALS__", plurals),
        "tests/__init__.py": "",
        "tests/helpers.py": HELPERS,
        "tests/test_api.py": _tests(entities),
        "requirements.txt": "# stdlib only\n",
        ".env.example": "HOST=127.0.0.1\nPORT=8080\nDATABASE_PATH=./app.db\n",
        ".gitignore": "__pycache__/\n*.pyc\n.env\n*.db\n",
        "Dockerfile": (
            "FROM python:3.12-slim\nRUN useradd -m app\nWORKDIR /srv\nCOPY . /srv\nUSER app\n"
            "ENV HOST=0.0.0.0 PORT=8080\nEXPOSE 8080\nCMD [\"python\", \"-m\", \"app\"]\n"
        ),
    }


def render_store(entities: list[dict], *, buggy_delete: bool = False) -> str:
    _check(entities)
    body = DELETE_BUGGY if buggy_delete else DELETE_OK
    return STORE_TEMPLATE.replace("__ENTITIES__", _entities_literal(entities)).replace("__DELETE_BODY__", body)
