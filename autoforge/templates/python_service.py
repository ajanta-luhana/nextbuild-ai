SERVER = '''"""Minimal WSGI JSON API (generated by AutoForge AI)."""
import json
import os
import re

from app.store import ENTITIES, Store, ValidationError

MAX_BODY = 64 * 1024
ROUTES = {__PLURALS__}
_PATH = re.compile(r"^/api/([a-z0-9_]+)(?:/(\\d+))?$")


def _respond(start_response, status, payload):
    body = json.dumps(payload).encode("utf-8")
    start_response("%d %s" % (status, "OK" if status < 400 else "ERROR"),
                   [("Content-Type", "application/json"), ("Content-Length", str(len(body)))])
    return [body]


def _error(start_response, status, code, message, details=None):
    return _respond(start_response, status, {"error": {"code": code, "message": message, "details": details or []}})


def create_app(store=None):
    store = store or Store(os.environ.get("DATABASE_PATH", ":memory:"))

    def application(environ, start_response):
        method = environ.get("REQUEST_METHOD", "GET")
        path = environ.get("PATH_INFO", "/")
        if path == "/health":
            return _respond(start_response, 200, {"status": "ok"})
        m = _PATH.match(path)
        if not m or m.group(1) not in ROUTES:
            return _error(start_response, 404, "NOT_FOUND", "Unknown route")
        entity = ROUTES[m.group(1)]
        item_id = int(m.group(2)) if m.group(2) else None
        body = None
        if method in ("POST", "PUT", "PATCH"):
            try:
                length = int(environ.get("CONTENT_LENGTH") or 0)
            except ValueError:
                return _error(start_response, 400, "BAD_REQUEST", "Invalid Content-Length")
            if length > MAX_BODY:
                return _error(start_response, 413, "TOO_LARGE", "Request body too large")
            try:
                body = json.loads(environ["wsgi.input"].read(length) or b"null")
            except ValueError:
                return _error(start_response, 400, "BAD_JSON", "Body is not valid JSON")
        try:
            if item_id is None:
                if method == "GET":
                    return _respond(start_response, 200, {"items": store.list(entity)})
                if method == "POST":
                    return _respond(start_response, 201, store.create(entity, body))
                return _error(start_response, 405, "METHOD_NOT_ALLOWED", "Method not allowed")
            if method == "GET":
                item = store.get(entity, item_id)
            elif method in ("PUT", "PATCH"):
                item = store.update(entity, item_id, body)
            elif method == "DELETE":
                if store.delete(entity, item_id):
                    return _respond(start_response, 200, {"deleted": item_id})
                item = None
            else:
                return _error(start_response, 405, "METHOD_NOT_ALLOWED", "Method not allowed")
            if item is None:
                return _error(start_response, 404, "NOT_FOUND", "%s %d not found" % (entity, item_id))
            return _respond(start_response, 200, item)
        except ValidationError as exc:
            return _error(start_response, 422, "VALIDATION_ERROR", "Request could not be validated.", exc.errors)

    return application
'''

