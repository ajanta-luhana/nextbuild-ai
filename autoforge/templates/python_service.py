def plural(name: str) -> str:
    return name if name.endswith("s") else name + "s"


def _check(entities: list[dict]) -> None:
    for e in entities:
        if not _IDENT.match(e["name"]):
            raise ValueError(f"invalid entity name {e['name']!r}")
        for f in e["fields"]:
            if not _IDENT.match(f["name"]) or f["name"] == "id":
                raise ValueError(f"invalid field name {f['name']!r}")


def _entities_literal(entities: list[dict]) -> str:
    spec = {e["name"]: e["fields"] for e in entities}
    return repr(json.dumps(spec, sort_keys=True))


